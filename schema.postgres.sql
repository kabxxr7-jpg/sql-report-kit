-- PostgreSQL version of schema.sql (the fictional shop used by sql-report-kit).
-- Money is integer cents, stored as BIGINT (SQLite's INTEGER is 64-bit too; a 32-bit column would overflow on a
-- single line over about $21 million). Dates and timestamps use native types here (SQLite keeps ISO text):
-- customers.created_at is a DATE, orders.created_at and refunds.refunded_at are TIMESTAMP without time zone.
-- Create the database with LC_COLLATE 'C' so text sorts the same way it does in SQLite (byte order).

CREATE TABLE customers (
    id          INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name        TEXT NOT NULL,
    email       TEXT NOT NULL,
    city        TEXT NOT NULL,
    created_at  DATE NOT NULL            -- signup date
);

CREATE TABLE products (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    sku          TEXT NOT NULL UNIQUE,
    name         TEXT NOT NULL,
    category     TEXT NOT NULL,
    price_cents  BIGINT NOT NULL CHECK (price_cents >= 0)
);

CREATE TABLE orders (
    id           INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id  INTEGER NOT NULL REFERENCES customers(id),
    status       TEXT NOT NULL CHECK (status IN ('completed', 'cancelled', 'pending')),
    created_at   TIMESTAMP NOT NULL
);

CREATE TABLE order_items (
    id                INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_id          INTEGER NOT NULL REFERENCES orders(id),
    product_id        INTEGER NOT NULL REFERENCES products(id),
    quantity          INTEGER NOT NULL CHECK (quantity > 0),
    unit_price_cents  BIGINT NOT NULL CHECK (unit_price_cents >= 0)
);

CREATE TABLE refunds (
    id              INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    order_item_id   INTEGER NOT NULL REFERENCES order_items(id),
    amount_cents    BIGINT NOT NULL CHECK (amount_cents > 0),
    refunded_at     TIMESTAMP NOT NULL,
    reason          TEXT NOT NULL
);

CREATE INDEX idx_orders_created_at       ON orders(created_at);
CREATE INDEX idx_orders_customer_id      ON orders(customer_id);
CREATE INDEX idx_order_items_order_id    ON order_items(order_id);
CREATE INDEX idx_order_items_product_id  ON order_items(product_id);
CREATE INDEX idx_refunds_order_item_id   ON refunds(order_item_id);
